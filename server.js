    const playerObj = {
      id: playerId,
      name: (name || 'Contestant').slice(0, 16),
      avatar: avatar || '😎',
      score: 0,
      streak: 0,
      isBot: false,
      hasAnswered: false,
      lastAnswerIndex: null,
      socketId: socket.id
    };

    room.players[playerId] = playerObj;
    socket.join(cleanCode);
    socket.roomCode = cleanCode;

    // Acknowledge player
    socket.emit('player:joined_success', {
      roomCode: cleanCode,
      player: playerObj,
      state: room.state,
      mode: room.mode
    });

    // Notify room & host
