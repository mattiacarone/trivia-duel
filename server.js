    const totalPlayers = Object.keys(room.players).length;
    const answeredCount = Object.values(room.players).filter(p => p.hasAnswered).length;

    io.to(roomCode).emit('round:player_locked_in', {
      playerId,
      playerName: player.name,
      answeredCount,
      totalPlayers
    });

