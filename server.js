// Generate QR code for mobile join
async function createRoomQrCode(roomCode) {
  const playUrl = `http://${LOCAL_IP}:${PORT}/play?room=${roomCode}`;
  try {
    const dataUrl = await QRCode.toDataURL(playUrl, {
      margin: 1,
      color: {
        dark: '#120e29',
        light: '#ffffff'
      },
      width: 240
    });
    return { dataUrl, playUrl };
  } catch (err) {
    return { dataUrl: '', playUrl };
  }
}

