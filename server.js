// Random 4-letter room code generator (easy to type)
const ROOM_WORDS = ['DUEL', 'FEST', 'KICK', 'PLAY', 'WINS', 'EPIC', 'HAHA', 'QUIZ', 'NERD', 'HYPE', 'VIBE', 'COOL'];
function generateRoomCode() {
  const chosen = ROOM_WORDS[Math.floor(Math.random() * ROOM_WORDS.length)];
  if (!rooms.has(chosen)) return chosen;
  // Fallback random 4 letters
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  let code = '';
  for (let i = 0; i < 4; i++) {
    code += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return code;
}

